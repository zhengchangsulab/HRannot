#!/usr/bin/env python
import re,argparse,textwrap
parser=argparse.ArgumentParser(formatter_class=argparse.RawTextHelpFormatter)
parser.add_argument('-g','--genome',type=str,metavar='',required=True,help=textwrap.dedent('Required\nFile containing target genome sequences in fasta format.'))
parser.add_argument('-m','--splignh',type=str,metavar='',required=True,help=textwrap.dedent('Required\nList of output files of Splign for reference genomes. If multiple reference genomes are used, separated by comma “,”.'))
parser.add_argument('-c','--CDS',type=str,metavar='',required=True,help=textwrap.dedent('Required\nList of files (if more than two, separated by comma “,” in the corresponding order as for option -m, --splignh) containing gene names of CDS in each reference genome.'))
parser.add_argument('-p','--prefix',type=str,metavar='',required=True,help=textwrap.dedent('Required\nList of names of references genomes. If multiple reference genomes are used, separated by comma “,” in the corresponding order as for option -m, --splignh.'))
parser.add_argument('-r','--splignR',type=str,metavar='',required=True,help=textwrap.dedent('Required\nOutput file of Splign for RNA-seq data.'))
parser.add_argument('-b','--bedfile',type=str,metavar='',required=True,help=textwrap.dedent('Required\nOutput file of Bedtools containing the genome regions mapped by high-quality sequencing reads.'))
parser.add_argument('-f','--cutoff',type=str,metavar='',default='10',help=textwrap.dedent('Default=10\nMinimal number (an integer) of reads to support a pseudogenization mutation.'))
parser.add_argument('-n','--noncoding',type=str,metavar='',required=True,help=textwrap.dedent('Required\nOutput file of Infernal containing non-coding RNA sequences in the target genome.'))
parser.add_argument('-l','--minORFlen',type=str,default='300',metavar='',help=textwrap.dedent('Default=300\nMinimal length (nucleotide) of the open reading frames for a RNA-seq-supported gene.'))
parser.add_argument('-s','--minRNAsco',type=str,default='0.985',metavar='',help=textwrap.dedent('Default=0.985\nMinimal average identity (decimal <=1) between assembled RNA transcripts and mapped target genome regions by Splign.'))
parser.add_argument('-o','--overlap',type=str,default='0.95',metavar='',help=textwrap.dedent('Default=0.95\nMinimal overlap rate (a decimal) of a gene in the next nearest species to be considered.'))
parser.add_argument('-i','--identity',type=str,default='0.99',metavar='',help=textwrap.dedent('Default=0.99\nMinimal identity (a decimal) of a gene in the next nearest species to be considered.'))
args=parser.parse_args()

fp=open('HRannot.sh','w')
fp.write('echo \"### Start analyzing the results of splign for ref_based\"'+'\n')
ll=args.prefix.split(',')
for a in range(len(ll)):
    fp.write('ref.get_best1.py '+args.CDS.split(',')[a]+' '+args.splignh.split(',')[a]+' '+args.prefix.split(',')[a]+'\n')
    fp.write('sort -k2,2 -k5,5 -k3,3n -k4,4n best1_'+args.prefix.split(',')[a]+' > sorted_best1_'+args.prefix.split(',')[a]+'\n')
fp.write('ref.compare.py '+args.prefix+' '+args.overlap+' '+args.identity+' '+' > best1'+'\n')
fp.write('sort -k2,2 -k5,5 -k3,3n -k4,4n best1 > sorted_best1'+'\n')
fp.write('ref.get_best2.py > best2.gff3'+'\n')
fp.write('ref.get_cds.py best2.gff3 '+args.genome+' > cds.fa'+'\n')
fp.write('ref.find_ORF.py'+'\n')
fp.write('awk \'$3==\"gene\"{print $9}\' best2_pseudogene.gff3 > best2_pseudogene'+'\n')
fp.write('cat extend_log.txt | grep -f best2_pseudogene > best2_pseudogene_log'+'\n')
fp.write('grep -v \"notextend\" best2_pseudogene_log > best2_pseudogene_need_extend'+'\n')
fp.write('echo \"### Finish analyzing the results of splign for ref_based\"'+'\n')
fp.write('\n')
fp.write('echo \"### Start analyzing the results of splign for RNA_based\"'+'\n')
fp.write('rna.get_best1.py '+args.splignR+'\n')
fp.write('sort -k2,2 -k5,5 -k3,3n -k4,4n best1 > sorted.best1'+'\n')
fp.write('rna.get_pass.py '+args.minRNAsco+' > best1.pass.sort'+'\n')
fp.write('rna.get_best2.py > rna_based.gff3'+'\n')
fp.write('echo \"### Finish analyzing the results of splign for RNA_based\"'+'\n')
fp.write('\n')
fp.write('echo \"### Start getting the ref_based gff3\"'+'\n')
fp.write('ref.get_best3.py'+'\n')
fp.write('ref.check_extended1.py '+args.genome+' > test'+'\n')
fp.write('ref.get_cds.py test '+args.genome+' > test.fa'+'\n')
fp.write('ref.check_extended2.py > extended_pseudogene.gff3'+'\n')
fp.write('ref.get_cds.py extended_pseudogene.gff3 '+args.genome+' > extended_pseudogene_cds.fa'+'\n')
fp.write('ref.find_ORF1.py'+'\n')
fp.write('cat best2_truegene.gff3 extended_truegene.gff3 > final_truegene.gff3'+'\n')
fp.write('cat pseudogene_part1.gff3 pseudogene_part2.gff3 > final_pseudogene.gff3'+'\n')
fp.write('awk \'$4<'+args.cutoff+'{print $0}\' '+args.bedfile+' > notsupport.region'+'\n')
fp.write('ref.merge_bed.py notsupport.region > new.notsupport.region'+'\n')
fp.write('ref.check_pseudogene.py new.notsupport.region > shortreads_notsupport.pseudogene'+'\n')
fp.write('ref.get_best4.py > ref_based1.gff3'+'\n')
fp.write('ref.get_best5.py'+'\n')
fp.write('echo \"### Finish getting the ref_based gff3\"'+'\n')
fp.write('\n')
fp.write('echo \"### Start getting the rna_based_uniq gff3\"'+'\n')
fp.write('rna.merge_ref_rna.py > rna_uniq.gff3'+'\n')
fp.write('rna.check_non_coding.py '+args.noncoding+' > rna_uniq1.gff3'+'\n')
fp.write('rna.get_cds.py rna_uniq1.gff3 '+args.genome+' > rna_uniq_cds.fa'+'\n')
fp.write('rna.verify_gene.py '+args.minORFlen+'  > rna_uniq_good_orf.fa'+'\n')
fp.write('grep \">\" rna_uniq_good_orf.fa | sed \'s/.//\' > total.support'+'\n')
fp.write('rna.support.get_best2.py > rna_support.gff3'+'\n')
fp.write('rna.support.match_cds.py > rna_support1.gff3'+'\n')
fp.write('rna.support.get_best3.py > rna_support2.gff3'+'\n')
fp.write('rna.support.get_best4.py > rna_support3.gff3'+'\n')
fp.write('echo \"### Finish getting the rna_based_uniq gff3\"'+'\n')
fp.write('\n')
fp.write('echo \"### Start getting final protein coding genes and pseudogenes\"'+'\n')
fp.write('cat ref_true_gene.gff3 rna_support3.gff3 > tobe_check.gff3'+'\n')
fp.write('final.check.py tobe_check.gff3 > final.right.truegene.gff3'+'\n')
fp.write('final.check.py ref_pseudogene.gff3 > final.right.pseudogene.gff3'+'\n')
fp.write('echo \"### Finish getting the protein coding genes and pseudogenes\"'+'\n')
fp.write('\n')
fp.write('echo \"### Remove unnecessary files\"'+'\n')
fp.write('rm *best* pseudogene_* ref_* new_old.name extend_* extended_* cds.fa rna_* test* final_* short* total.support tobe_check.gff3 *.region'+'\n')
fp.write('echo \"### Finish removing unnecessary files\"'+'\n')
fp.write('echo \"Finished!\"'+'\n')
fp.close()
